  /* True when `word` appears at the start of a word in `haystack`. Suffixes
     are fine ("deck" hits "decks"); prefixes are not ("miss" cannot be
     tripped by "dismiss"). */
  function startsWord(haystack, word) {
    var from = 0;
    while (true) {
      var at = haystack.indexOf(word, from);
      if (at === -1) return false;
      if (at === 0 || !isWordChar(haystack.charAt(at - 1))) return true;
      from = at + 1;
    }
  }

  function pickPool(text) {
    var haystack = String(text).toLowerCase();
    for (var i = 0; i < KEYWORDS.length; i += 1) {
      var entry = KEYWORDS[i];
      for (var j = 0; j < entry.words.length; j += 1) {
        if (startsWord(haystack, entry.words[j])) return entry.pool;
      }
    }
    return 'generic';
  }

  function nextReply(text) {
    var name = pickPool(text);
    var pool = SCRIPT.replies[name];
    if (!pool || !pool.length) {
      name = 'generic';
      pool = SCRIPT.replies.generic;
    }
    if (!pool || !pool.length) return SCRIPT.opening;

    var index = poolCursor[name] || 0;
    if (index >= pool.length) index = 0;
    poolCursor[name] = index + 1;
    return pool[index];
  }

  /* Longer answers take longer to "type", within a fixed band, plus jitter. */
  function typingDelay(reply) {
    if (prefersReducedMotion()) return TYPE_REDUCED;
    var base = TYPE_MIN + reply.length * TYPE_PER_CHAR;
    if (base > TYPE_MAX) base = TYPE_MAX;
    var value = base + randomInt(-TYPE_JITTER, TYPE_JITTER);
    return value < TYPE_MIN ? TYPE_MIN : value;
  }

