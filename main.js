  function pushMessage(role, text) {
    var ts = Date.now();
    messages.push({ role: role, text: text, ts: ts });

    if (thread) {
      /* live messages get the entrance animation; the seeded thread rendered
         by renderAll() deliberately does not, so opening the chat shows the
         existing conversation already in place rather than replaying it. */
      var node = buildBubble(role, text, ts);
      if (!prefersReducedMotion()) node.classList.add(CLASS.bubbleNew);
      thread.appendChild(node);
    }

    while (messages.length > MAX_MESSAGES) {
      messages.shift();
      var oldest = thread ? qs('[data-msg]', thread) : null;
      if (oldest && oldest.parentNode) oldest.parentNode.removeChild(oldest);
    }

    persist();
    scrollToBottom(false);
  }

