  /* Accepts anything; returns only well-formed messages. Restored data is
     untrusted — it came from localStorage, which the user can edit, and it
     may be a v1 record with no `ts` at all. Missing or nonsense timestamps
     are back-filled a minute apart, ending at now. */
  function sanitise(raw) {
    var clean = [];
    if (Object.prototype.toString.call(raw) !== '[object Array]') return clean;

    for (var i = 0; i < raw.length; i += 1) {
      var item = raw[i];
      if (!item || typeof item.text !== 'string') continue;
      var text = item.text.slice(0, MAX_LEN);
      if (!text.replace(/\s+/g, '')) continue;
      var ts = typeof item.ts === 'number' && isFinite(item.ts) && item.ts > 0 ? item.ts : null;
      clean.push({ role: item.role === 'user' ? 'user' : 'jaxx', text: text, ts: ts });
    }

    if (clean.length > MAX_MESSAGES) clean = clean.slice(clean.length - MAX_MESSAGES);

    var now = Date.now();
    for (var j = 0; j < clean.length; j += 1) {
      if (clean[j].ts === null) clean[j].ts = now - (clean.length - 1 - j) * 60000;
    }
    return clean;
  }

