/* ==========================================================================
   JAXX — woven paper texture. Paints <canvas class="weave">. Owns no CSS.
   Purely decorative: if it never runs, flat --paper carries the page.

   THE WEAVE, in one paragraph — every tunable lives in CONFIG, nothing else.
   One small tile is generated once then repeated with createPattern; nothing
   is drawn per pixel across the viewport. The tile is a grid of cells "pitch"
   px square, each holding a slice of a horizontal fibre (weft) and a vertical
   one (warp); a fibre is a lit crown (white) plus a shadowed gap (ink). In
   each cell one of the two is drawn last, and that parity flips with every
   step in both directions — a plain weave. Per-fibre and per-cell jitter stop
   it reading as graph paper; a one-device-pixel speckle finishes it as stock.
   Coarser/finer: pitch. Stronger/weaker: dark + light. Grainier: speckle.
   ========================================================================== */
(function () {
  'use strict';

  var CONFIG = {
    tile: 144,           /* tile edge, CSS px — must be an even multiple of pitch */
    pitch: 3,            /* fibre spacing, CSS px — the weave's coarseness        */
    fibreWidth: 0.55,    /* share of the pitch taken by the lit crown             */
    dark: 0.020,         /* alpha of the ink shadow in the gap between fibres     */
    light: 0.30,         /* alpha of the white highlight on the fibre crown       */
    jitter: 0.18,        /* 0..1 random alpha variation, per fibre                */
    cellJitter: 0.35,    /* 0..1 random alpha variation, per crossing             */
    slub: 0.20,          /* 0..1 random thickness variation, per fibre            */
    weftOver: 1,         /* which cell parity puts the weft over the warp         */
    speckle: 0.07,       /* share of device pixels given a grain speck            */
    speckleDark: 0.048,  /* alpha of a dark speck                                 */
    speckleLight: 0.11,  /* alpha of a light speck                                */
    seed: 20250825,      /* fixed seed — the tile is identical on every paint     */
    maxDpr: 2,           /* cap: a 3x phone gets a 2x tile, not a 3x one          */
    debounce: 150,       /* ms to let a resize settle before repainting           */
    heightSlack: 140,    /* px of height-only change to ignore (mobile URL bar)   */
    paperFallback: '#F6F4F6'
  };

  var canvas = null, tile = null, tileKey = '', timer = null;
  var lastW = -1, lastH = -1, lastDpr = 0, bound = false;

  function seeded(s) {                       /* deterministic LCG */
    var v = s >>> 0;
    return function () { v = (v * 1664525 + 1013904223) >>> 0; return v / 4294967296; };
  }
  function ratio() {
    var d = Math.min(window.devicePixelRatio || 1, CONFIG.maxDpr);
    return d > 0 ? d : 1;
  }

  function paperColour() {                   /* --paper stays the only source of truth */
    var v = '';
    try {
      v = window.getComputedStyle(document.documentElement).getPropertyValue('--paper');
    } catch (e) { v = ''; }
    v = String(v || '').replace(/^\s+|\s+$/g, '');
    return v || CONFIG.paperFallback;
  }

  function buildTile(dpr) {
    var T = CONFIG.tile, P = CONFIG.pitch, n = Math.round(T / P), i, r, c, k;
    var el = document.createElement('canvas');
    el.width = Math.round(T * dpr);
    el.height = Math.round(T * dpr);
    var g = el.getContext && el.getContext('2d');
    if (!g) { return null; }
    g.scale(dpr, dpr);                       /* the tile is authored in CSS units */
    g.fillStyle = paperColour();
    g.fillRect(0, 0, T, T);

    var rand = seeded(CONFIG.seed);
    var av = [], ah = [], cv = [], ch = [];  /* per-fibre alpha + thickness */
    function slub() {
      var t = P * CONFIG.fibreWidth * (1 + CONFIG.slub * (rand() * 2 - 1));
      return Math.max(P * 0.25, Math.min(P * 0.85, t));
    }
    for (i = 0; i < n; i++) { av.push(1 - CONFIG.jitter * rand()); cv.push(slub()); }
    for (i = 0; i < n; i++) { ah.push(1 - CONFIG.jitter * rand()); ch.push(slub()); }
    function weft(row, col, a) {             /* horizontal fibre, one cell wide */
      var y = row * P, x = col * P, t = ch[row];
      a *= ah[row];
      g.fillStyle = 'rgba(255,255,255,' + (CONFIG.light * a) + ')';
      g.fillRect(x, y, P, t);
      g.fillStyle = 'rgba(22,19,32,' + (CONFIG.dark * a) + ')';
      g.fillRect(x, y + t, P, P - t);
    }
    function warp(col, row, a) {             /* vertical fibre, one cell tall */
      var y = row * P, x = col * P, t = cv[col];
      a *= av[col];
      g.fillStyle = 'rgba(255,255,255,' + (CONFIG.light * a) + ')';
      g.fillRect(x, y, t, P);
      g.fillStyle = 'rgba(22,19,32,' + (CONFIG.dark * a) + ')';
      g.fillRect(x + t, y, P - t, P);
    }
    for (r = 0; r < n; r++) {
      for (c = 0; c < n; c++) {
        k = 1 - CONFIG.cellJitter * rand();   /* whichever is drawn last sits on top */
        if (((r + c) & 1) === CONFIG.weftOver) { warp(c, r, k); weft(r, c, k); }
        else { weft(r, c, k); warp(c, r, k); }
      }
    }
    var px = 1 / dpr, dev = T * dpr, dots = Math.round(dev * dev * CONFIG.speckle);
    for (i = 0; i < dots; i++) {              /* grain: exactly one device pixel each */
      g.fillStyle = rand() < 0.5
        ? 'rgba(22,19,32,' + CONFIG.speckleDark + ')'
        : 'rgba(255,255,255,' + CONFIG.speckleLight + ')';
      g.fillRect(Math.floor(rand() * dev) * px, Math.floor(rand() * dev) * px, px, px);
    }
    return el;
  }

  /* leave nothing half-painted: an empty canvas falls back to flat --paper */
  function blank() {
    try { if (canvas) { canvas.width = 1; canvas.height = 1; } } catch (e) { /* done */ }
  }

  function paint() {
    try {
      canvas = document.querySelector('.weave');
      if (!canvas || !canvas.getContext) { return; }
      var ctx = canvas.getContext('2d');
      if (!ctx) { return; }
      var cssW = canvas.clientWidth || window.innerWidth || 0;
      var cssH = canvas.clientHeight || window.innerHeight || 0;
      if (!cssW || !cssH) { return; }
      var dpr = ratio();
      var key = dpr + '|' + paperColour();   /* only rebuild when dpr or --paper moves */
      if (!tile || tileKey !== key) { tile = buildTile(dpr); tileKey = key; }
      if (!tile) { blank(); return; }
      /* backing store in device pixels, filled under an identity transform, so
         one tile pixel lands on exactly one device pixel — crisp on retina */
      canvas.width = Math.round(cssW * dpr);
      canvas.height = Math.round(cssH * dpr);
      var pattern = ctx.createPattern(tile, 'repeat');
      if (!pattern) { blank(); return; }
      ctx.setTransform(1, 0, 0, 1, 0, 0);
      ctx.fillStyle = pattern;
      ctx.fillRect(0, 0, canvas.width, canvas.height);
      lastW = cssW; lastH = cssH; lastDpr = dpr;
    } catch (e) { blank(); }
  }

  function onResize() {
    if (timer) { clearTimeout(timer); }
    timer = setTimeout(function () {
      timer = null;
      var w = canvas ? canvas.clientWidth : window.innerWidth;
      var h = canvas ? canvas.clientHeight : window.innerHeight;
      /* mobile chrome hiding/showing only nudges the height — not worth a repaint */
      if (w === lastW && ratio() === lastDpr &&
          Math.abs(h - lastH) <= CONFIG.heightSlack) { return; }
      paint();
    }, CONFIG.debounce);
  }

  function destroy() {
    try {
      if (timer) { clearTimeout(timer); timer = null; }
      if (bound) { window.removeEventListener('resize', onResize, false); bound = false; }
      blank();
      tile = null; tileKey = ''; lastW = -1; lastH = -1; lastDpr = 0;
    } catch (e) { /* silent */ }
  }

  function init() {
    paint();
    if (!bound) { window.addEventListener('resize', onResize, false); bound = true; }
  }

  try {
    window.JAXXWeave = { paint: paint, destroy: destroy };
    if (document.readyState === 'loading') {
      document.addEventListener('DOMContentLoaded', init, false);
    } else { init(); }
  } catch (e) { /* silent — the page still has --paper */ }
}());


/* ==========================================================================
   JAXX — shell.js
   Vanilla, no dependencies, loaded with `defer`.
   Everything here is progressive enhancement: if this file never runs the
   page is still fully readable, navigable and scrollable.
     1. sticky-header shade past 24px
     2. smooth anchor scrolling that clears the sticky header
     3. mobile menu toggle
     4. gentle fade-up reveal (opt-in, added by JS so it can never get stuck)
   ========================================================================== */
(function () {
  'use strict';

  var doc = document;
  var header = doc.getElementById('site-header');
  var toggle = header ? header.querySelector('.site-header__toggle') : null;
  var nav = doc.getElementById('site-menu');

  var reduceMotionQuery =
    window.matchMedia ? window.matchMedia('(prefers-reduced-motion: reduce)') : null;

  function prefersReducedMotion() {
    return !!(reduceMotionQuery && reduceMotionQuery.matches);
  }

  function headerHeight() {
    return header ? Math.round(header.getBoundingClientRect().height) : 0;
  }

  /* ------------------------------------------------------------------------
     1. Sticky header shade
     ------------------------------------------------------------------------ */
  (function stickyHeader() {
    if (!header) return;

    var ticking = false;

    function apply() {
      ticking = false;
      var scrolled = (window.pageYOffset || doc.documentElement.scrollTop) > 24;
      /* `is-stuck` is the name build/landing.css styles */
      header.classList.toggle('is-stuck', scrolled);
    }

    function onScroll() {
      if (ticking) return;
      ticking = true;
      window.requestAnimationFrame(apply);
    }

    window.addEventListener('scroll', onScroll, { passive: true });
    apply();
  })();

  /* ------------------------------------------------------------------------
     2. Mobile menu  (declared before the anchor handler so closeMenu exists)
     The drawer only exists below the tablet breakpoint; above it the nav is a
     plain row and the toggle is display:none, so these handlers idle.
     ------------------------------------------------------------------------ */
  function menuIsOpen() {
    return !!header && header.classList.contains('is-open');
  }

  function setMenu(open) {
    if (!header || !toggle || !nav) return;
    header.classList.toggle('is-open', open);
    nav.classList.toggle('is-open', open);
    toggle.setAttribute('aria-expanded', open ? 'true' : 'false');
    toggle.setAttribute('aria-label', open ? 'Close menu' : 'Open menu');
  }

  function closeMenu() {
    if (menuIsOpen()) setMenu(false);
  }

  if (toggle && nav && header) {
    toggle.addEventListener('click', function () {
      setMenu(!menuIsOpen());
    });

    doc.addEventListener('keydown', function (event) {
      if (event.key === 'Escape' && menuIsOpen()) {
        setMenu(false);
        toggle.focus();
      }
    });

    doc.addEventListener('click', function (event) {
      if (!menuIsOpen()) return;
      if (header.contains(event.target)) return;
      setMenu(false);
    });

    /* the drawer is a phone-only affordance — collapsing back to the tablet
       layout with it still open would leave aria-expanded lying */
    if (window.matchMedia) {
      var tabletQuery = window.matchMedia('(min-width: 768px)');
      var onTabletChange = function (event) {
        if (event.matches) setMenu(false);
      };
      if (tabletQuery.addEventListener) {
        tabletQuery.addEventListener('change', onTabletChange);
      } else if (tabletQuery.addListener) {
        tabletQuery.addListener(onTabletChange);
      }
    }
  }

  /* ------------------------------------------------------------------------
     3. Smooth anchor scrolling
     ------------------------------------------------------------------------ */
  doc.addEventListener('click', function (event) {
    if (event.defaultPrevented) return;
    if (event.button !== 0 || event.metaKey || event.ctrlKey || event.shiftKey || event.altKey) {
      return;
    }

    var link = event.target.closest ? event.target.closest('a[href]') : null;
    if (!link) return;
    if (link.target && link.target !== '_self') return;

    /* anything that opens the chat is not a navigation — chat.js owns it */
    if (link.hasAttribute('data-chat-open')) return;

    var href = link.getAttribute('href');
    if (!href || href.charAt(0) !== '#' || href === '#') return;

    var id = decodeURIComponent(href.slice(1));
    var target = doc.getElementById(id);
    if (!target) return;

    event.preventDefault();
    closeMenu();

    var top =
      target.getBoundingClientRect().top +
      (window.pageYOffset || doc.documentElement.scrollTop) -
      headerHeight() -
      16;

    if (top < 0) top = 0;

    try {
      window.scrollTo({
        top: top,
        behavior: prefersReducedMotion() ? 'auto' : 'smooth'
      });
    } catch (err) {
      window.scrollTo(0, top);
    }

    // keep the URL and the keyboard in sync without a second, un-offset jump
    if (window.history && window.history.pushState) {
      window.history.pushState(null, '', href);
    }

    if (!target.hasAttribute('tabindex')) {
      target.setAttribute('tabindex', '-1');
    }
    target.focus({ preventScroll: true });
  });

  /* ------------------------------------------------------------------------
     4. Fade-up reveal
     Sections carry `.reveal` in the markup but stay visible until this script
     adds `.has-reveal` to <html> — so a JS failure can never hide content.
     ------------------------------------------------------------------------ */
  (function reveal() {
    var items = doc.querySelectorAll('.reveal');
    if (!items.length) return;

    if (prefersReducedMotion() || !('IntersectionObserver' in window)) return;

    try {
      var observer = new IntersectionObserver(
        function (entries) {
          entries.forEach(function (entry) {
            if (!entry.isIntersecting) return;
            entry.target.classList.add('is-in');
            observer.unobserve(entry.target);
          });
        },
        { rootMargin: '0px 0px -12% 0px', threshold: 0.06 }
      );

      doc.documentElement.classList.add('has-reveal');

      Array.prototype.forEach.call(items, function (item) {
        observer.observe(item);
      });
    } catch (err) {
      // never leave anything hidden
      doc.documentElement.classList.remove('has-reveal');
    }
  })();
})();


